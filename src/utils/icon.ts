function extensionOf(name: string) {
  return name.split('.').pop()?.toLowerCase() || ''
}

function hasSuffix(name: string, suffixes: string[]) {
  const lower = name.toLowerCase()
  return suffixes.some(suffix => lower.endsWith(suffix))
}

export function openListFileIconName(name: string, isDir = false): OpenListFileIconName {
  if (isDir)
    return 'folder'

  const ext = extensionOf(name)
  if (appleExts.has(ext))
    return 'apple'
  if (windowsExts.has(ext))
    return 'windows'
  if (androidExts.has(ext))
    return 'android'
  if (databaseExts.has(ext))
    return 'database'
  if (bookExts.has(ext))
    return 'book'
  if (hasSuffix(name, ['.iso', '.img', '.bin']))
    return 'disc'
  if (markdownExts.has(ext))
    return 'markdown'
  if (pdfExts.has(ext))
    return 'pdf'
  if (docExts.has(ext))
    return 'word'
  if (xlsExts.has(ext))
    return 'excel'
  if (pptExts.has(ext))
    return 'ppt'
  if (psdExts.has(ext))
    return 'psd'
  if (aiExts.has(ext))
    return 'ai'
  if (linkExts.has(ext))
    return 'link'
  if (castExts.has(ext))
    return 'cast'
  if (hasSuffix(name, archiveSuffixes))
    return 'zip'
  if (musicExts.has(ext))
    return 'music'
  if (playExts.has(ext))
    return 'play'
  if (imageExts.has(ext))
    return 'image'
  if (textExts.has(ext))
    return 'text'
  return 'minus'
}

export function openListFileIconHref(name: string, isDir = false) {
  return fileIconHrefs[openListFileIconName(name, isDir)]
}
